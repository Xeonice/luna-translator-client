#!/usr/bin/env python3
"""Check generated Rust DTO and design-token artifacts without modifying them."""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = '/* Generated from tokens.json. Values follow the confirmed material baseline. */\n'


def render_tokens(tokens):
    if set(tokens) != {'dark', 'light'} or not all(isinstance(tokens[x], dict) and tokens[x] for x in tokens):
        raise ValueError('Token source must contain nonempty dark and light maps')
    rows = [HEADER.rstrip()]
    for theme, selector in [('dark', ':root'), ('light', 'html[data-theme="light"]')]:
        rows.append(selector + ' {')
        for key, value in tokens[theme].items():
            if not re.fullmatch(r'--[a-z][a-z0-9-]*', key) or not isinstance(value, str) or any(c in value for c in '{};\n\r'):
                raise ValueError('Invalid CSS token declaration: ' + str(key))
            rows.append(f'  {key}: {value};')
        rows.append('}')
    return '\n'.join(rows) + '\n'


def design_token_errors(root, tokens):
    material = (root / 'docs/design/first-product-v1/material-tokens.css').read_text()
    style = (root / 'docs/design/first-product-v1/styles.css').read_text()
    errors = []
    for theme, selector in [('dark', ':root'), ('light', 'html[data-theme="light"]')]:
        match = re.search(re.escape(selector) + r'\s*\{([^}]+)\}', material)
        if not match:
            raise ValueError('Confirmed material theme block is missing: ' + theme)
        expected = dict(re.findall(r'(--material-[a-z-]+)\s*:\s*([^;]+);', match.group(1)))
        if theme == 'dark':
            shade = re.search(r'--product-window-shade\s*:\s*([^;]+);', style)
        else:
            block = re.search(r'html\[data-theme="light"\]\s*\{([^}]+)\}', style)
            shade = re.search(r'--product-window-shade\s*:\s*([^;]+);', block.group(1)) if block else None
        if not shade:
            raise ValueError('Confirmed product window shade is missing: ' + theme)
        expected['--material-window-shade'] = shade.group(1).strip()
        if tokens[theme] != expected:
            errors.append('Product token source differs from confirmed design values: ' + theme)
    return errors


def verify(root=ROOT, *, tokens_only=False):
    errors, artifacts = [], {}
    source = root / 'apps/desktop/src/ui/tokens/tokens.json'
    generated = root / 'apps/desktop/src/ui/tokens/generated.css'
    tokens = json.loads(source.read_text())
    expected = render_tokens(tokens)
    errors.extend(design_token_errors(root, tokens))
    if generated.read_text() != expected:
        errors.append('Generated CSS differs from tokens.json; regenerate it without changing token values')
    artifacts['tokens_source_sha256'] = hashlib.sha256(source.read_bytes()).hexdigest()
    artifacts['tokens_css_sha256'] = hashlib.sha256(generated.read_bytes()).hexdigest()
    if not tokens_only:
        command = ['cargo', 'run', '--quiet', '--locked', '--offline', '-p', 'app-core', '--example', 'export_contracts']
        result = subprocess.run(command, cwd=root, text=True, capture_output=True, timeout=600)
        artifacts.update(command=command, exporter_exit_code=result.returncode, exporter_stderr=result.stderr)
        dto = root / 'apps/desktop/src/bridge/contracts.generated.ts'
        if result.returncode:
            errors.append('Actual Rust DTO exporter failed')
        elif not result.stdout.startswith('// Generated by app-core. Do not edit.\n') or 'export type Command' not in result.stdout:
            errors.append('Rust DTO exporter produced empty or invalid declarations')
        elif dto.read_text() != result.stdout:
            errors.append('Generated TS contracts drifted from actual Rust DTO definitions')
        artifacts['dto_generated_sha256'] = hashlib.sha256(dto.read_bytes()).hexdigest()
        artifacts['dto_export_sha256'] = hashlib.sha256(result.stdout.encode()).hexdigest()
    return {'schema_version': 1, 'status': 'failed' if errors else 'passed', 'errors': errors, **artifacts}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tokens-only', action='store_true')
    args = parser.parse_args()
    try:
        result = verify(tokens_only=args.tokens_only)
    except (OSError, ValueError, subprocess.TimeoutExpired) as error:
        result = {'status': 'failed', 'errors': [str(error)]}
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return int(result['status'] != 'passed')


if __name__ == '__main__':
    raise SystemExit(main())
